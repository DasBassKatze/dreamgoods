def note_for(model_id, name="", description=""):
    """(описание, max_res) для модели; без совпадения — первое предложение описания из каталога Polza."""
    hay = f"{model_id} {name}"
    for rx, res, text in _compiled:
        if rx.search(hay):
            return text, res
    d = re.sub(r"\s+", " ", str(description or "")).strip()
    if d:
        first = re.split(r"(?<=[.!?])\s", d, 1)[0]
        return (first if len(first) <= 220 else first[:217].rstrip() + "…"), None
    return "", None
